-- Initial schema for the umelka-stats-simple Supabase project.
-- Recreates every table the app uses (players, seasons, matches, feedback) together with
-- RLS policies. It only creates objects and is safe to run more than once.
-- Run it in the NEW project only; the old project is left untouched.

create extension if not exists pgcrypto;

-- Players -------------------------------------------------------------------
create table if not exists public.players (
    id          uuid primary key default gen_random_uuid(),
    name        text not null,
    -- Season goal target shown in GoalProgress (read as goal_target in usePlayerCalculatedScore)
    goal_target integer,
    created_at  timestamptz not null default now()
);

-- Seasons -------------------------------------------------------------------
-- ids are numeric; the app hard-codes some of them (e.g. season 7 for live matches)
create table if not exists public.seasons (
    id         bigint generated by default as identity primary key,
    name       text not null,
    created_at timestamptz not null default now()
);

-- Matches -------------------------------------------------------------------
create table if not exists public.matches (
    id               uuid primary key default gen_random_uuid(),
    date             date not null,
    team_a           uuid[] not null default '{}',
    team_b           uuid[] not null default '{}',
    score_a          integer not null default 0,
    score_b          integer not null default 0,
    -- { "<player id>": <count> }
    goals            jsonb not null default '{}'::jsonb,
    assists          jsonb not null default '{}'::jsonb,
    comments         text,
    season_id        bigint references public.seasons(id),
    -- Who took the jerseys home to wash and bring to the next match
    jersey_player_id uuid references public.players(id) on delete set null,
    created_at       timestamptz not null default now()
);

create index if not exists matches_season_id_idx on public.matches (season_id);
create index if not exists matches_date_idx on public.matches (date);

-- Feedback ------------------------------------------------------------------
create table if not exists public.feedback (
    id         bigint generated by default as identity primary key,
    message    text not null,
    name       text,
    created_at timestamptz not null default now()
);

-- Grants --------------------------------------------------------------------
-- Explicit so the tables are reachable through the API even if default privileges change.
grant usage on schema public to anon, authenticated;
grant select on public.players, public.seasons, public.matches to anon, authenticated;
grant insert, update, delete on public.players, public.seasons, public.matches to authenticated;
grant insert on public.feedback to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Row level security --------------------------------------------------------
alter table public.players  enable row level security;
alter table public.seasons  enable row level security;
alter table public.matches  enable row level security;
alter table public.feedback enable row level security;

-- Everyone can read the stats
drop policy if exists "Public read" on public.players;
create policy "Public read" on public.players for select to anon, authenticated using (true);
drop policy if exists "Public read" on public.seasons;
create policy "Public read" on public.seasons for select to anon, authenticated using (true);
drop policy if exists "Public read" on public.matches;
create policy "Public read" on public.matches for select to anon, authenticated using (true);

-- Only logged-in users (admin pages behind useAuthGuard) can change data
drop policy if exists "Authenticated write" on public.players;
create policy "Authenticated write" on public.players for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated write" on public.seasons;
create policy "Authenticated write" on public.seasons for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated write" on public.matches;
create policy "Authenticated write" on public.matches for all to authenticated using (true) with check (true);

-- Anyone can send feedback, nobody can read it through the API (view it in the dashboard)
drop policy if exists "Anyone can send feedback" on public.feedback;
create policy "Anyone can send feedback" on public.feedback for insert to anon, authenticated with check (true);
